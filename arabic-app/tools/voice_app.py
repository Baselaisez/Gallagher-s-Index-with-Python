#!/usr/bin/env python3
"""voice_app.py — v349: «Uygulamanın sesi / The app's own voice». Pre-renders every story's narration at BUILD time, so a
learner whose phone has no Arabic voice still hears every sentence — and nothing of an engine ships or runs on the phone.

    python3 tools/voice_app.py                    # every story → prototype/narration/<story>/app/ (unchanged chapters kept)
    python3 tools/voice_app.py --package DIR      # one story package
    python3 tools/voice_app.py --check            # the test set through this path: the phonemes eSpeak reports, scored
    python3 tools/voice_app.py --stand-in DIR     # no engine: a tone per sentence (the delivery path alone, for a smoke run)
    python3 tools/voice_app.py --verify           # (release gate, no engine) every chapter's audio matches the text it reads
    python3 tools/voice_app.py --out DIR          # render into DIR (the Pages workflow: the site's narration/, cached between runs)
    python3 tools/voice_app.py --key              # one hash of everything the render depends on (the CI cache key)
    python3 tools/voice_app.py --engine azure     # (v355) the same reading spoken by a hosted neural voice (tools/voice_azure.py;
                                                  #   needs AZURE_SPEECH_KEY + AZURE_SPEECH_REGION — the owner's decision; build time only)

The rendered shelf is a BUILD PRODUCT (~100 MB): it is not in git. The repository keeps one short sample story
(al-asad-wa-al-far, for the smoke suite); the Pages workflow renders the whole shelf at deploy time into the site.

The reading is the app's own (tools/voice_eval.py: every written vowel and ending, hamzat al-waṣl elided in connected
speech, the article assimilated, stress by the classical rule) handed to eSpeak NG as PHONEMES ([[…]]), so the engine's
letter-to-sound rules — which misread shadda and never elide the waṣl — are not used at all. eSpeak runs here as a tool
(tools/voice_espeak.mjs, npm `espeak-ng`, GPL-3.0-or-later); only its audio ships.

Output per story: `app/ch<N>.m4a` (AAC-LC, mono 16 kHz, 24 kb/s: plays in every browser and WebView; a formant voice
carries nothing above 8 kHz worth the bytes) + `app/index.json` {voice, chapters: {n: {file, bytes, ms, key, sentences:
{id: [startMs, endMs]}}}}; and the shelf's `prototype/narration/app-voice.json` {voice, licence, stories: {id: bytes}}.
A chapter is re-rendered only when its sent text or the reading changed (`key`).
"""
import argparse, hashlib, io, json, math, os, pathlib, shutil, struct, subprocess, sys, tempfile, time, wave

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import narration_generate as ng          # noqa: E402  (the shelf walk, SEND347's twin, the WAV join)
import voice_eval as ve                  # noqa: E402  (the reading)

OUT = ROOT / "prototype/narration"
READING_VERSION = "v349.1"
VOICE = {"id": "app349", "name": "eSpeak NG ar — the app's reading", "engine": "eSpeak NG 1.52 (WebAssembly, npm espeak-ng 1.0.2), run at build time",
         "licence": "audio generated by a GPL-3.0-or-later tool; the output is not a covered work (GPLv3 §2); no engine ships",
         "automatic": True, "format": "m4a", "codec": "AAC-LC mono 16 kHz 24 kb/s"}
GAP_MS = 250
# (v355) the engine that speaks the reading: eSpeak NG (default, as v349) or a hosted neural voice through tools/voice_azure.py.
ENGINE = os.environ.get("QISSA_VOICE_ENGINE", "espeak")
AZURE = {"id": "azure355", "name": "Microsoft Azure neural voice — the app's reading", "engine": "Azure AI Speech, voice "
         + os.environ.get("AZURE_TTS_VOICE", "ar-SA-HamedNeural") + ", fed the app's reading as IPA phonemes, run at build time",
         "licence": "audio generated with the owner's Azure Speech resource (Microsoft's terms: the voice must be disclosed as synthetic — "
                    "the app labels it «otomatik / automatic»); no engine ships", "automatic": True, "format": "m4a", "codec": "AAC-LC mono 16 kHz 24 kb/s"}
NOTE = {"espeak": "A generated voice: the app's rule-based reading of the written vowels (every ending pronounced, «وَصْلًا»), "
                  "spoken by a formant synthesiser. Not a teacher's recitation; ظ is said as ذ (the engine has no emphatic ẓ).",
        "azure": "A generated voice: the app's rule-based reading of the written vowels (every ending pronounced, «وَصْلًا») sent as "
                 "phonemes to a hosted neural voice (Microsoft Azure). Automatic, not a teacher's recitation."}


def voice():
    return AZURE if ENGINE == "azure" else VOICE


def chapter_jobs(pkg):
    by = {}
    for m, n, sid, text in ng.walk(pkg):
        by.setdefault((m["id"], n), []).append((sid, text))
    return by


def key_of(sens):
    h = hashlib.sha1(READING_VERSION.encode())
    for sid, text in sens:
        h.update(f"{sid}\t{text}\n".encode())
    return h.hexdigest()[:12] + ("" if ENGINE == "espeak" else "-" + ENGINE)


def encode(wav_bytes, out):
    """WAV → AAC .m4a (mono 16 kHz 24 kb/s, the moov atom first so the first sentence plays before the file is in)."""
    with tempfile.NamedTemporaryFile(suffix=".wav", delete=False) as t:
        t.write(wav_bytes)
    try:
        subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-i", t.name, "-ac", "1", "-ar", "16000", "-c:a", "aac",
                        "-b:a", "24k", "-movflags", "+faststart", str(out)], check=True)
    finally:
        os.unlink(t.name)


def tone_wav(text, rate=16000):
    """stand-in: a soft 440 Hz tone, as long as the sentence would take at ~12 letters a second."""
    n = int(rate * max(0.6, len([c for c in text if "ء" <= c <= "ي"]) / 12))
    frames = b"".join(struct.pack("<h", int(4000 * math.sin(2 * math.pi * 440 * i / rate) * min(1, i / 800, (n - i) / 800))) for i in range(n))
    b = io.BytesIO()
    with wave.open(b, "wb") as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(rate); w.writeframes(frames)
    return b.getvalue()


def render(jobs, tmp):
    """jobs: [(out_wav, phoneme_input)] → eSpeak through the node helper, one process for the batch."""
    spec = pathlib.Path(tmp) / "jobs.json"
    spec.write_text(json.dumps([{"out": str(o), "input": i} for o, i in jobs], ensure_ascii=False), encoding="utf-8")
    r = subprocess.run(["node", str(ROOT / "tools/voice_espeak.mjs"), str(spec)], capture_output=True, text=True)
    if r.returncode:
        sys.exit("eSpeak NG could not run: " + (r.stderr.strip() or r.stdout.strip()))


def build_story(pkg, stand_in=False, out_root=OUT, force=False):
    st_id = json.loads((pkg / "manifest.json").read_text(encoding="utf-8"))["id"]
    d = out_root / st_id / "app"
    idx_path = d / "index.json"
    old = json.loads(idx_path.read_text(encoding="utf-8")) if idx_path.is_file() else {"chapters": {}}
    index = {"voice": "stand-in" if stand_in else voice()["id"], "chapters": {}}
    d.mkdir(parents=True, exist_ok=True)
    stats = {"rendered": 0, "kept": 0, "sentences": 0, "audio_ms": 0, "synth_ms": 0}
    for (pid, n), sens in chapter_jobs(pkg).items():
        k = key_of(sens) + ("-tone" if stand_in else "")
        prev = old["chapters"].get(str(n))
        f = d / f"ch{n}.m4a"
        if prev and prev.get("key") == k and f.is_file() and not force:
            index["chapters"][str(n)] = prev; stats["kept"] += 1; continue
        t0 = time.time()
        with tempfile.TemporaryDirectory() as tmp:
            if stand_in:
                clips = [tone_wav(text) for _, text in sens]
            elif ENGINE == "azure":
                import voice_azure
                clips = [voice_azure.synthesize(text)[0] for _, text in sens]
            else:
                jobs = [(pathlib.Path(tmp) / f"{i}.wav", ve.espeak_phonemes(text)) for i, (_, text) in enumerate(sens)]
                render(jobs, tmp)
                clips = [o.read_bytes() for o, _ in jobs]
            audio, spans, total = ng.wav_join(clips, GAP_MS)
            synth = (time.time() - t0) * 1000
            encode(audio, f)
        index["chapters"][str(n)] = {"file": f.name, "bytes": f.stat().st_size, "ms": total, "key": k,
                                     "sentences": {sid: sp for (sid, _), sp in zip(sens, spans)}}
        stats["rendered"] += 1; stats["sentences"] += len(sens); stats["audio_ms"] += total; stats["synth_ms"] += synth
    for f in d.glob("ch*.m4a"):                       # a chapter that no longer exists
        if f.stem[2:] not in index["chapters"]:
            f.unlink()
    idx_path.write_text(json.dumps(index, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    return st_id, sum(c["bytes"] for c in index["chapters"].values()), stats


def shelf_key():
    """everything a render depends on: the reading version, this tool, the reading, eSpeak's pinned version, every sent text."""
    h = hashlib.sha1(READING_VERSION.encode())
    h.update(ENGINE.encode() + os.environ.get("AZURE_TTS_VOICE", "").encode())
    for f in ("tools/voice_app.py", "tools/voice_eval.py", "tools/voice_espeak.mjs", "tools/voice_azure.py"):
        h.update((ROOT / f).read_bytes())
    pj = json.loads((ROOT / "package.json").read_text(encoding="utf-8"))
    h.update(str((pj.get("devDependencies") or {}).get("espeak-ng")).encode())
    for pkg in ng.packages():
        for (pid, n), sens in chapter_jobs(pkg).items():
            h.update(f"{pid}/{n}:{key_of(sens)}\n".encode())
    return h.hexdigest()[:16]


def write_shelf(out_root=OUT):
    stories, total, ms = {}, 0, 0
    for idx in sorted(out_root.glob("*/app/index.json")):
        j = json.loads(idx.read_text(encoding="utf-8"))
        b = sum(c["bytes"] for c in j["chapters"].values()) + idx.stat().st_size
        stories[idx.parent.parent.name] = b; total += b; ms += sum(c["ms"] for c in j["chapters"].values())
    shelf = dict(voice(), reading=READING_VERSION, stories=stories, bytes=total, minutes=round(ms / 60000, 1), note=NOTE[ENGINE])
    (out_root / "app-voice.json").write_text(json.dumps(shelf, ensure_ascii=False, indent=1), encoding="utf-8")
    return shelf


def check():
    """the 30-sentence test set through this very path: eSpeak is asked which phonemes it will say (--ipa), and they
    are scored against the expected readings — the evidence that what is heard is what is written."""
    rows = ve.load_set()
    with tempfile.TemporaryDirectory() as tmp:
        jobs = [(pathlib.Path(tmp) / f"{r['id']}.wav", ve.espeak_phonemes(r["text"])) for r in rows]
        t0 = time.time(); render(jobs, tmp); synth = time.time() - t0
        audio = sum(wave.open(str(o)).getnframes() / 22050 for o, _ in jobs)
        spec = pathlib.Path(tmp) / "ipa.mjs"
        spec.write_text("""import fs from 'fs'; import path from 'path'; import { pathToFileURL } from 'url';
const m = process.env.ESPEAK_NG_MODULE || (process.env.NODE_PATH || '').split(path.delimiter).concat(['node_modules']).map(r => path.join(r, 'espeak-ng/dist/espeak-ng.js')).find(p => fs.existsSync(p));
const E = (await import(pathToFileURL(path.resolve(m)).href)).default; const rows = JSON.parse(fs.readFileSync(process.argv[2], 'utf8')); let o = '';
for (const r of rows) { const e = await E({ arguments: ['--phonout', '/o.txt', '-q', '--ipa', '-v', 'ar', r.input], print: () => {}, printErr: () => {} }); o += r.id + '\\t' + e.FS.readFile('/o.txt', { encoding: 'utf8' }).replace(/\\s+/g, ' ').trim() + '\\n'; }
fs.writeFileSync(process.argv[3], o);""", encoding="utf-8")
        inp = pathlib.Path(tmp) / "in.json"
        inp.write_text(json.dumps([{"id": r["id"], "input": ve.espeak_phonemes(r["text"])} for r in rows], ensure_ascii=False), encoding="utf-8")
        tsv = pathlib.Path(tmp) / "app-voice.tsv"
        subprocess.run(["node", str(spec), str(inp), str(tsv)], check=True, cwd=str(ROOT))
        res = subprocess.run([sys.executable, str(ROOT / "tools/voice_eval.py"), "--score", str(tsv)], capture_output=True, text=True).stdout
    print(res.strip())
    print(f"build-time speed: {synth:.1f} s for {audio:.0f} s of audio — real-time factor {synth / audio:.3f} (this container, one process)")
    return 0 if "all endings right 30/30" in res else 1


def verify(only=None, out=OUT):
    """every chapter (of the shelf, or of one package) has its app-voice audio, rendered from today's sent text (the key)."""
    stale = []
    for pkg in ng.packages(only):
        st_id = json.loads((pkg / "manifest.json").read_text(encoding="utf-8"))["id"]
        idx = out / st_id / "app" / "index.json"
        ix = json.loads(idx.read_text(encoding="utf-8")) if idx.is_file() else {"chapters": {}}
        for (pid, n), sens in chapter_jobs(pkg).items():
            e = ix["chapters"].get(str(n))
            if not e or e.get("key") != key_of(sens) or not (out / st_id / "app" / e["file"]).is_file():
                stale.append(f"{st_id} ch{n}")
    if stale:
        print(f"{len(stale)} chapter(s) without current app-voice audio: {', '.join(stale[:8])}{' …' if len(stale) > 8 else ''}\n"
              "  → python3 tools/voice_app.py   (node + npm espeak-ng + ffmpeg)")
        return 1
    print("app voice: every chapter " + ("of " + only if only else "of the shelf") + " is current")
    return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--package"); ap.add_argument("--check", action="store_true"); ap.add_argument("--verify", action="store_true")
    ap.add_argument("--out", help="render into this folder instead of prototype/narration"); ap.add_argument("--key", action="store_true")
    ap.add_argument("--stand-in", metavar="OUT", help="write tone packs into OUT (not prototype/narration)")
    ap.add_argument("--force", action="store_true"); ap.add_argument("--jobs", type=int, default=os.cpu_count() or 1)
    ap.add_argument("--engine", choices=("espeak", "azure"), help="who speaks the reading (default: $QISSA_VOICE_ENGINE or espeak)")
    a = ap.parse_args()
    global ENGINE
    if a.engine:
        ENGINE = a.engine
    if ENGINE not in ("espeak", "azure"):
        sys.exit("unknown engine " + ENGINE)
    if a.check:
        return check()
    if a.key:
        print(shelf_key()); return 0
    if a.verify:
        return verify(a.package, pathlib.Path(a.out).resolve() if a.out else OUT)
    if not shutil.which("ffmpeg"):
        sys.exit("ffmpeg is needed to write the .m4a files")
    out = pathlib.Path(a.stand_in or a.out).resolve() if (a.stand_in or a.out) else OUT
    if ENGINE == "azure" and not a.stand_in and not (os.environ.get("AZURE_SPEECH_KEY") and os.environ.get("AZURE_SPEECH_REGION")):
        sys.exit("--engine azure needs AZURE_SPEECH_KEY and AZURE_SPEECH_REGION (the owner's Speech resource) — nothing was sent")
    pkgs = list(ng.packages(a.package))
    t0 = time.time(); agg = {"rendered": 0, "kept": 0, "sentences": 0, "audio_ms": 0, "synth_ms": 0}
    from concurrent.futures import ThreadPoolExecutor
    with ThreadPoolExecutor(max_workers=max(1, a.jobs)) as ex:
        for st_id, b, s in ex.map(lambda p: build_story(p, bool(a.stand_in), out, a.force), pkgs):
            for k in agg:
                agg[k] += s[k]
            if s["rendered"]:
                print(f"{st_id:44} {b / 1e6:6.2f} MB  {s['rendered']} chapter(s) rendered, {s['kept']} kept")
    shelf = write_shelf(out)
    if ENGINE == "azure":
        import voice_azure
        print(f"azure: {len(voice_azure.FALLBACKS)} sentence(s) sent as plain text (phonemes refused)")
    print(f"\nshelf: {len(shelf['stories'])} stories, {shelf['bytes'] / 1e6:.1f} MB, {shelf['minutes']} minutes of audio; this run rendered {agg['rendered']} chapters "
          f"({agg['sentences']} sentences, {agg['audio_ms'] / 3.6e6:.2f} h of audio) in {time.time() - t0:.0f} s")
    return 0


if __name__ == "__main__":
    sys.exit(main())
